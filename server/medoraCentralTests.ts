let centralSeededPromise: Promise<void> | null = null;

export async function ensureCentralTestsSeeded(db: Firestore): Promise<void> {
  if (!centralSeededPromise) {
    centralSeededPromise = (async () => {
      try {
        const snap = await db.collection('medora_central_lab_tests').limit(1).get();
        if (!snap.empty) return;
        const batch = db.batch();
        for (const item of MEDORA_CENTRAL_LAB_TESTS) {
          batch.set(db.doc(`medora_central_lab_tests/${item.centralTestId}`), {
            ...item,
            createdAt: FieldValue.serverTimestamp(),
            updatedAt: FieldValue.serverTimestamp(),
          });
        }
        await batch.commit();
      } catch (err) {
        centralSeededPromise = null;
        console.warn('[MEDORA][CentralLabTestsSeed] warning:', err);
      }
    })();
  }
  await centralSeededPromise;
}
